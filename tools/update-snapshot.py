#!/usr/bin/env python3
"""Refresh feed-snapshot.js, the offline fallback used when the live
gdg.community.dev feed cannot be reached. Run: python3 tools/update-snapshot.py"""
import json, os, urllib.request

API = "https://gdg.community.dev/api"
CH, SLUG = 318, "gdg-vizag"
FIELDS = "id,title,start_date,end_date,venue_name,event_type_title,cropped_picture_url,cropped_banner_url,url,cohost_registration_url,description_short,tags"

def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)

def events(status, order):
    q = f"{API}/event_slim/for_chapter/{CH}/?page_size=500&status={status}&include_cohosted_events=true&visible_on_parent_chapter_only=true&order={order}&fields={FIELDS}"
    rows = get(q)["results"]
    for r in rows:
        r.pop("title_translated", None); r.pop("description_short_translated", None)
        if r.get("description_short"): r["description_short"] = r["description_short"][:220]
    return rows

team = [{"first_name": m["user"]["first_name"], "last_name": m["user"]["last_name"], "title": m.get("title"), "avatar": (m["user"].get("avatar") or {}).get("url")} for m in get(f"{API}/chapter_slim/{SLUG}/team/")]
chapter = get(f"{API}/chapter_slim/{SLUG}/")
snap = {"live": events("Live", "start_date"), "done": events("Completed", "-start_date"), "team": team,
        "chapter": {"members_count": chapter.get("members_count"), "logo": chapter.get("cropped_logo_url"), "banner": chapter.get("cropped_banner_url")}}
out = os.path.join(os.path.dirname(__file__), "..", "feed-snapshot.js")
with open(out, "w") as f:
    f.write("// Generated by tools/update-snapshot.py. Offline fallback for feed.js.\nwindow.FEED_SNAPSHOT = " + json.dumps(snap, separators=(",", ":")) + ";\n")
print("events:", len(snap["live"]), "upcoming,", len(snap["done"]), "completed; members:", snap["chapter"]["members_count"])
